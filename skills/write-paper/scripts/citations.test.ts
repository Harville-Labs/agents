import { describe, expect, it } from "bun:test";
import { main, type Runtime } from "./citations.ts";
import { LEDGER_COLUMNS } from "./ledger.ts";

const ATTENTION = { type: "article", title: "Attention Is All You Need", publisher: "arXiv", issued: { "date-parts": [[2017]] } };

function runtime(files: Record<string, string>, metadata: Record<string, unknown> = {}) {
	const stdout: string[] = [];
	const stderr: string[] = [];
	const requested: string[] = [];
	const rt: Runtime = {
		fetch: async (url) => {
			requested.push(url);
			const doi = url.slice("https://doi.org/".length);
			return doi in metadata ? Response.json(metadata[doi]) : new Response("not found", { status: 404 });
		},
		read: async (path) => files[path] ?? null,
		write: async (path, text) => {
			files[path] = text;
		},
		texFiles: async () => Object.keys(files).filter((path) => path.endsWith(".tex")),
		stdout: (line) => stdout.push(line),
		stderr: (line) => stderr.push(line),
	};
	return { rt, files, stdout, stderr, requested };
}

function ledger(...rows: string[]): string {
	return [LEDGER_COLUMNS.join("\t"), ...rows].join("\n");
}

const ATTENTION_ROW = "vaswani2017\tarxiv:1706.03762\tAttention Is All You Need\tTransformers drop recurrence\t§3\tfull";

describe("citations build", () => {
	it("writes references.bib from resolved metadata and passes the check", async () => {
		const { rt, files, stdout, stderr, requested } = runtime(
			{ "p/sources.tsv": ledger(ATTENTION_ROW), "p/main.tex": "\\cite{vaswani2017}" },
			{ "10.48550/arXiv.1706.03762": ATTENTION },
		);
		expect(await main(["build", "p"], rt)).toBe(0);
		expect(stderr).toEqual([]);
		expect(requested).toEqual(["https://doi.org/10.48550/arXiv.1706.03762"]);
		expect(files["p/references.bib"]).toStartWith("% Generated by citations build");
		expect(files["p/references.bib"]).toContain("@misc{vaswani2017,");
		expect(stdout.at(-1)).toBe("ok: 1 sources, 1 ledger rows, 1 cited");
	});

	it("refuses a DOI whose title is a different paper and writes nothing", async () => {
		const { rt, files, stderr } = runtime(
			{ "p/sources.tsv": ledger("k\tdoi:10.1000/x\tA Paper That Does Not Exist\ts\tw\tfull") },
			{ "10.1000/x": { title: "Something Else Entirely" } },
		);
		expect(await main(["build", "p"], rt)).toBe(1);
		expect(stderr).toEqual([
			'error: sources.tsv:2 (k): 10.1000/x is "Something Else Entirely", not "A Paper That Does Not Exist". Fix the DOI or the title',
		]);
		expect(files["p/references.bib"]).toBeUndefined();
	});

	it("reports a DOI that does not resolve", async () => {
		const { rt, stderr } = runtime({ "p/sources.tsv": ledger("k\tdoi:10.1000/missing\tT\ts\tw\tfull") });
		expect(await main(["build", "p"], rt)).toBe(1);
		expect(stderr[0]).toContain("10.1000/missing does not resolve");
	});

	it("leaves manual sources to manual.bib without fetching them", async () => {
		const { rt, stdout, requested } = runtime({
			"p/sources.tsv": ledger("web\tmanual\tProject page\ts\thome page\tfull"),
			"p/manual.bib": "@misc{web, title={Project page}}",
			"p/main.tex": "\\cite{web}",
		});
		expect(await main(["build", "p"], rt)).toBe(0);
		expect(requested).toEqual([]);
		expect(stdout).toContain("manual entries a human must check by hand: web");
	});
});

describe("citations check", () => {
	it("fails when the paper cites a key the ledger does not hold", async () => {
		const { rt, stderr } = runtime({
			"p/sources.tsv": ledger(ATTENTION_ROW),
			"p/references.bib": "@misc{vaswani2017, title={x}}",
			"p/main.tex": "\\cite{vaswani2017,smith2020}",
		});
		expect(await main(["check", "p"], rt)).toBe(1);
		expect(stderr).toEqual([
			"error: main.tex: cites smith2020, which has no row in sources.tsv. Add a checked row; never cite from memory",
		]);
	});

	it("fails when a ledger source was never built into references.bib", async () => {
		const { rt, stderr } = runtime({ "p/sources.tsv": ledger(ATTENTION_ROW), "p/main.tex": "" });
		expect(await main(["check", "p"], rt)).toBe(1);
		expect(stderr).toEqual(["error: sources.tsv:2 (vaswani2017): not in references.bib. Run citations build"]);
	});

	it("lists uncited sources and abstract-only rows without failing", async () => {
		const { rt, stdout } = runtime({
			"p/sources.tsv": ledger(ATTENTION_ROW.replace(/full$/, "abstract")),
			"p/references.bib": "@misc{vaswani2017, title={x}}",
			"p/main.tex": "",
		});
		expect(await main(["check", "p"], rt)).toBe(0);
		expect(stdout).toEqual([
			"ok: 1 sources, 1 ledger rows, 0 cited",
			"not cited (remove or cite): vaswani2017",
			"abstract-only rows (background claims only): vaswani2017:2",
		]);
	});

	it("explains a missing ledger and prints usage on bad arguments", async () => {
		const missing = runtime({});
		expect(await main(["check", "p"], missing.rt)).toBe(1);
		expect(missing.stderr[0]).toContain("sources.tsv is missing");
		const bad = runtime({});
		expect(await main(["publish"], bad.rt)).toBe(2);
		expect(bad.stderr[0]).toStartWith("Usage: citations");
	});
});
