import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";
import { type Csl, firstText, titlesMatch, toBibtex } from "./bib.ts";
import { type LedgerRow, parseLedger } from "./ledger.ts";
import { bibKeys, citeKeys } from "./tex.ts";

export type Runtime = {
	readonly fetch: (url: string, init: RequestInit) => Promise<Response>;
	readonly read: (path: string) => Promise<string | null>;
	readonly write: (path: string, text: string) => Promise<void>;
	readonly texFiles: (dir: string) => Promise<string[]>;
	readonly stdout: (line: string) => void;
	readonly stderr: (line: string) => void;
};

const USAGE = `Usage: citations <build|check> <paper-dir>

  build  Resolve every doi: and arxiv: source in sources.tsv through doi.org,
         check each title against the ledger, write references.bib, then check.
  check  Offline. Check that every \\cite key is in the ledger and a .bib file,
         and that every ledger row is complete.`;

const GENERATED_HEADER = "% Generated by citations build from sources.tsv. Do not edit; rerun the build.\n\n";

export async function main(argv: readonly string[], rt: Runtime): Promise<number> {
	const [command, dir] = argv;
	if ((command !== "build" && command !== "check") || !dir || argv.length !== 2) {
		(command === "--help" || command === "-h" ? rt.stdout : rt.stderr)(USAGE);
		return command === "--help" || command === "-h" ? 0 : 2;
	}
	const ledgerText = await rt.read(join(dir, "sources.tsv"));
	if (ledgerText === null) {
		rt.stderr(`error: ${join(dir, "sources.tsv")} is missing. Copy it from the skill's template folder.`);
		return 1;
	}
	const ledger = parseLedger(ledgerText);
	if (ledger.errors.length > 0) return fail(rt, ledger.errors);
	if (command === "build") {
		const built = await build(ledger.rows, rt);
		if (built.errors.length > 0) return fail(rt, built.errors);
		await rt.write(join(dir, "references.bib"), GENERATED_HEADER + built.entries.join("\n"));
		rt.stdout(`wrote ${join(dir, "references.bib")} with ${built.entries.length} entries`);
	}
	return check(dir, ledger.rows, rt);
}

function fail(rt: Runtime, errors: readonly string[]): number {
	for (const error of errors) rt.stderr(`error: ${error}`);
	return 1;
}

function uniqueByKey(rows: readonly LedgerRow[]): LedgerRow[] {
	const seen = new Map<string, LedgerRow>();
	for (const row of rows) if (!seen.has(row.key)) seen.set(row.key, row);
	return [...seen.values()].sort((a, b) => a.key.localeCompare(b.key));
}

async function build(rows: readonly LedgerRow[], rt: Runtime) {
	const entries: string[] = [];
	const errors: string[] = [];
	for (const row of uniqueByKey(rows)) {
		if (row.source.kind !== "doi") continue;
		const { doi } = row.source;
		const at = `sources.tsv:${row.line} (${row.key})`;
		let response: Response;
		try {
			response = await rt.fetch(`https://doi.org/${encodeURI(doi)}`, {
				headers: {
					accept: "application/vnd.citationstyles.csl+json",
					"user-agent": "hl-write-paper-citations (https://github.com/Harville-Labs/agents)",
				},
				redirect: "follow",
				signal: AbortSignal.timeout(30_000),
			});
		} catch (error) {
			errors.push(`${at}: could not reach doi.org for ${doi} (${String(error)}). Check the network and rerun`);
			continue;
		}
		if (response.status === 404) {
			errors.push(`${at}: ${doi} does not resolve. Copy the DOI from the source's own page; never guess one`);
			continue;
		}
		if (!response.ok) {
			errors.push(`${at}: doi.org answered ${response.status} for ${doi}. Rerun later`);
			continue;
		}
		let csl: Csl;
		try {
			csl = (await response.json()) as Csl;
		} catch {
			errors.push(`${at}: ${doi} did not return citation metadata. Cite it as manual and check it by hand`);
			continue;
		}
		const resolved = firstText(csl.title);
		if (!titlesMatch(row.title, resolved)) {
			errors.push(`${at}: ${doi} is "${resolved}", not "${row.title}". Fix the DOI or the title`);
			continue;
		}
		entries.push(toBibtex(row.key, doi, csl));
	}
	return { entries, errors };
}

async function check(dir: string, rows: readonly LedgerRow[], rt: Runtime): Promise<number> {
	const generated = await rt.read(join(dir, "references.bib"));
	const manual = (await rt.read(join(dir, "manual.bib"))) ?? "";
	const generatedKeys = new Set(generated === null ? [] : bibKeys(generated));
	const manualKeys = new Set(bibKeys(manual));
	const errors: string[] = [];
	const ledgerKeys = new Set(rows.map((row) => row.key));

	for (const row of uniqueByKey(rows)) {
		const at = `sources.tsv:${row.line} (${row.key})`;
		if (row.source.kind === "doi" && !generatedKeys.has(row.key))
			errors.push(`${at}: not in references.bib. Run citations build`);
		if (row.source.kind === "manual" && !manualKeys.has(row.key))
			errors.push(`${at}: source is manual but manual.bib has no entry ${row.key}`);
		if (generatedKeys.has(row.key) && manualKeys.has(row.key))
			errors.push(`${at}: defined in both references.bib and manual.bib. Keep one`);
	}
	for (const key of manualKeys)
		if (!ledgerKeys.has(key)) errors.push(`manual.bib: ${key} has no row in sources.tsv`);

	const cited = new Set<string>();
	for (const file of await rt.texFiles(dir)) {
		const tex = (await rt.read(file)) ?? "";
		for (const key of citeKeys(tex)) {
			cited.add(key);
			if (!ledgerKeys.has(key))
				errors.push(`${relative(dir, file)}: cites ${key}, which has no row in sources.tsv. Add a checked row; never cite from memory`);
		}
	}
	if (errors.length > 0) return fail(rt, errors);

	const unused = [...ledgerKeys].filter((key) => !cited.has(key)).sort();
	const manualRows = uniqueByKey(rows).filter((row) => row.source.kind === "manual");
	const abstractOnly = rows.filter((row) => row.read === "abstract");
	rt.stdout(`ok: ${ledgerKeys.size} sources, ${rows.length} ledger rows, ${cited.size} cited`);
	if (unused.length > 0) rt.stdout(`not cited (remove or cite): ${unused.join(", ")}`);
	if (manualRows.length > 0)
		rt.stdout(`manual entries a human must check by hand: ${manualRows.map((row) => row.key).join(", ")}`);
	if (abstractOnly.length > 0)
		rt.stdout(
			`abstract-only rows (background claims only): ${abstractOnly.map((row) => `${row.key}:${row.line}`).join(", ")}`,
		);
	return 0;
}

async function texFiles(dir: string): Promise<string[]> {
	const entries = await readdir(dir, { recursive: true, withFileTypes: true });
	return entries
		.filter((entry) => entry.isFile() && entry.name.endsWith(".tex"))
		.map((entry) => join(entry.parentPath, entry.name))
		.sort();
}

export async function readOrNull(path: string): Promise<string | null> {
	try {
		return await readFile(path, "utf8");
	} catch (error) {
		if ((error as NodeJS.ErrnoException).code === "ENOENT") return null;
		throw error;
	}
}

export const nodeRuntime: Runtime = {
	fetch: (url, init) => fetch(url, init),
	read: readOrNull,
	write: (path, text) => writeFile(path, text),
	texFiles,
	stdout: (line) => console.log(line),
	stderr: (line) => console.error(line),
};

if (import.meta.main) process.exit(await main(process.argv.slice(2), nodeRuntime));
